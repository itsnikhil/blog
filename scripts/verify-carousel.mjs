import fs from 'node:fs';
import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
const html=fs.readFileSync('dist/posts/screen-to-screen-navigation-understanding-with-ai/index.html','utf8');
const dom=new JSDOM(html,{url:'http://localhost/blog/',runScripts:'outside-only'});
const {window}=dom;
window.eval(fs.readFileSync('dist/js/carousel.js','utf8'));
window.document.dispatchEvent(new window.Event('DOMContentLoaded'));
const c=window.document.querySelector('#app-navigation');
const count=()=>c.querySelector('.current-slide').textContent;
assert.equal(count(),'1');
c.querySelector('.next').click();assert.equal(count(),'2');
assert.equal(c.querySelectorAll('.carousel-slide')[0].getAttribute('aria-hidden'),'true');
assert.equal(c.querySelectorAll('.carousel-slide')[1].getAttribute('aria-hidden'),'false');
assert.equal(c.querySelectorAll('.indicator')[1].getAttribute('aria-current'),'true');
assert(c.querySelector('.carousel-status').textContent.startsWith('Slide 2 of '));
c.querySelector('.prev').click();assert.equal(count(),'1');
c.querySelectorAll('.indicator')[2].click();assert.equal(count(),'3');
c.dispatchEvent(new window.KeyboardEvent('keydown',{key:'ArrowRight'}));assert.equal(count(),'4');
c.dispatchEvent(new window.KeyboardEvent('keydown',{key:'ArrowLeft'}));assert.equal(count(),'3');
assert.equal(c.getAttribute('tabindex'),'0');
window.close();
console.log('PASS: carousel next, previous, indicators, keyboard and focusability.');
