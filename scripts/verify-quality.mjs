import fs from 'node:fs';
import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {entries} from '../src/lib/content.js';
const home=new JSDOM(fs.readFileSync('dist/index.html','utf8')).window.document;
assert.equal(home.querySelectorAll('h1').length,1);
assert.equal(home.querySelectorAll('#writing h2').length,1);
assert.equal(home.querySelectorAll('.topic-list li').length,12);
assert(home.querySelector('a[href="/blog/tags/"]'));
for(const path of ['index.html','posts/index.html','projects/index.html','tags/index.html',...entries.map(p=>`${p.route}/index.html`)]){
 const document=new JSDOM(fs.readFileSync(`dist/${path}`,'utf8')).window.document;
 assert(document.querySelector('.skip-link[href="#main-content"]'),path);
 assert(document.querySelector('main#main-content[tabindex="-1"]'),path);
 assert(document.querySelector('nav[aria-label="Main navigation"]'),path);
 const description=document.querySelector('meta[name="description"]').content;
 assert(!/!?\[[^\]]*\]\(|```|{{<|<[^>]+>/.test(description),`Unrendered description: ${path}`);
}
const projects=new JSDOM(fs.readFileSync('dist/projects/index.html','utf8')).window.document;
assert.equal(projects.querySelectorAll('h1').length,1);
assert(projects.body.textContent.includes('Journal Fitbit App'));
assert(projects.body.textContent.includes('total internal reflection'));
console.log('PASS: semantic home/project headings, skip navigation, 12-topic discovery, plain-text metadata and verified project corrections.');
const archive=new JSDOM(fs.readFileSync('dist/posts/index.html','utf8')).window.document;
assert(archive.querySelector('.archive-position').textContent.includes('Page 1 of 2'));
assert.equal(archive.querySelectorAll('.entry-preview p').length,10);
const article=new JSDOM(fs.readFileSync('dist/posts/screen-to-screen-navigation-understanding-with-ai/index.html','utf8')).window.document;
assert(article.querySelector('.article-toc summary').textContent==='On this page');
for(const link of article.querySelectorAll('.article-toc a'))assert(article.getElementById(link.hash.slice(1)),`TOC target ${link.hash}`);
assert(article.querySelector('[data-preview-comments]').textContent.includes('Comments are disabled in this preview'));
const css=fs.readFileSync('dist/css/refinements.css','utf8');
assert(css.includes('#footer{position:static'));
assert(css.includes('#projects .project-list .project-item p{display:block'));
console.log('PASS: archive summaries/page location, TOC anchor targets, preview comments note and legacy layout overrides.');
for(const entry of entries)assert(entry.excerpt.length<=180,`Excerpt too long: ${entry.route}`);
const composer=entries.find(e=>e.route==='posts/oai-app-composer');
assert(composer.html.includes('still needs network access'));
assert(composer.html.includes('Accuracy update'));
assert(!composer.html.includes('completely offline'));
const jwt=entries.find(e=>e.route==='posts/implementing-silent-refresh-of-jwt');
assert(jwt.html.includes('Authorization checks whether'));
assert(jwt.html.includes('still need CSRF defenses'));
assert(jwt.html.includes('Security update'));
console.log('PASS: bounded excerpts and source-verified technical correction presence.');
const correctedDocument=new JSDOM(fs.readFileSync('dist/posts/oai-app-composer/index.html','utf8')).window.document;
assert(correctedDocument.querySelector('time[itemprop="dateModified"]'));
assert(correctedDocument.body.textContent.includes('git clone https://github.com/itsnikhil/oai-app-composer.git'));
assert(correctedDocument.body.textContent.includes('normally http://localhost:3000'));
console.log('PASS: visible updated date and source-verified setup instructions.');
assert(css.includes('#header #nav li:not(:first-child){display:block!important;margin:0;padding:0'));
console.log('PASS: mobile navigation resets inherited 70px indentation.');
